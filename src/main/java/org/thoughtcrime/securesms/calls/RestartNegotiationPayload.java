package org.thoughtcrime.securesms.calls;

import androidx.annotation.Nullable;
import java.util.UUID;
import org.json.JSONException;
import org.json.JSONObject;

/**
 * Wire-format codec for the ICE-restart renegotiation payload that flows between Android and Core's
 * {@code send_call_update} RPC. The schema is a small, deliberately boring JSON object so that
 * other clients (notably Desktop's {@code calls-webapp}) can adopt the same contract without taking
 * a dependency on Java types.
 *
 * <pre>
 *   { "id":   "&lt;uuid identifying one transaction&gt;",
 *     "type": "offer" | "answer",
 *     "sdp":  "&lt;raw SDP blob&gt;" }
 * </pre>
 *
 * The {@code id} field is generated by the offerer and echoed unchanged by the answerer so that
 * callers can discard stale answers that do not match their currently in-flight transaction.
 */
public final class RestartNegotiationPayload {

  public static final String FIELD_ID = "id";
  public static final String FIELD_TYPE = "type";
  public static final String FIELD_SDP = "sdp";

  public static final String TYPE_OFFER = "offer";
  public static final String TYPE_ANSWER = "answer";

  private RestartNegotiationPayload() {}

  /**
   * Build an offer payload with a fresh transaction id. The id can later be replayed by the
   * answerer via {@link #buildAnswer(String, String)} so the caller can validate that the answer
   * belongs to its current in-flight transaction.
   */
  @Nullable
  public static String buildOffer(String sdp) {
    if (sdp == null) return null;
    return buildInternal(generateId(), TYPE_OFFER, sdp);
  }

  /**
   * Build an offer payload with a caller-supplied id. Used when the coordinator has already
   * generated a UUID and needs to surface the same id back in an answer payload built later.
   */
  @Nullable
  public static String buildOfferWithId(String id, String sdp) {
    if (id == null || sdp == null) return null;
    return buildInternal(id, TYPE_OFFER, sdp);
  }

  /** Build an answer payload that echoes the offerer's {@code id} verbatim. */
  @Nullable
  public static String buildAnswer(String id, String sdp) {
    if (id == null || sdp == null) return null;
    return buildInternal(id, TYPE_ANSWER, sdp);
  }

  @Nullable
  private static String buildInternal(String id, String type, String sdp) {
    try {
      JSONObject obj = new JSONObject();
      obj.put(FIELD_ID, id);
      obj.put(FIELD_TYPE, type);
      obj.put(FIELD_SDP, sdp);
      return obj.toString();
    } catch (JSONException e) {
      return null;
    }
  }

  public static String generateId() {
    return UUID.randomUUID().toString();
  }

  /**
   * Parsed representation of an incoming renegotiation payload. {@link #id}, {@link #type} and
   * {@link #sdp} are all non-null/empty when {@link #valid} is {@code true}.
   */
  public static final class Parsed {
    public final boolean valid;
    public final String id;
    public final String type;
    public final String sdp;

    private Parsed(boolean valid, String id, String type, String sdp) {
      this.valid = valid;
      this.id = id;
      this.type = type;
      this.sdp = sdp;
    }

    public boolean isOffer() {
      return valid && TYPE_OFFER.equals(type);
    }

    public boolean isAnswer() {
      return valid && TYPE_ANSWER.equals(type);
    }
  }

  /** Parse a payload received from the peer. */
  public static Parsed parse(String payload) {
    if (payload == null || payload.isEmpty()) {
      return new Parsed(false, null, null, null);
    }
    try {
      JSONObject obj = new JSONObject(payload);
      String id = obj.optString(FIELD_ID, null);
      String type = obj.optString(FIELD_TYPE, null);
      String sdp = obj.optString(FIELD_SDP, null);
      boolean valid =
          id != null
              && !id.isEmpty()
              && type != null
              && !type.isEmpty()
              && sdp != null
              && !sdp.isEmpty();
      return new Parsed(valid, id, type, sdp);
    } catch (JSONException e) {
      return new Parsed(false, null, null, null);
    }
  }
}
